import { devices, expect, test, webkit } from '@playwright/test'
import { cellCenter } from '../src/shared/map.ts'

test('mobile can customize a solo game and see the timed match statistics', async ({ browser, baseURL }) => {
  test.setTimeout(100_000)
  const mobile = process.env.MOBILE_BROWSER === 'webkit' ? await webkit.launch() : browser
  const context = await mobile.newContext(devices[mobile === browser ? 'Pixel 7' : 'iPhone 14'])
  try {
    const page = await context.newPage()
    await page.goto(baseURL!)
    await page.getByRole('button', { name: 'Match settings', exact: true }).tap()
    const menu = page.getByRole('dialog', { name: 'Match settings' })
    await menu.getByLabel('Battlefield').selectOption('ironbreak-pass')
    await expect(menu.locator('[name="gold-count"]')).toHaveValue('7')
    await expect(menu.getByLabel('Random starting positions')).toBeChecked()
    await menu.getByLabel('Time limit (minutes)').fill('1')
    await menu.getByLabel('Starting gold', { exact: true }).fill('123')
    for (const resource of ['gold', 'wood', 'stone']) {
      await menu.locator('[name="' + resource + '-count"]').fill('0')
    }
    await menu.getByRole('button', { name: 'Save settings' }).tap()
    await page.reload()
    await page.getByRole('button', { name: 'Match settings', exact: true }).tap()
    await expect(menu.getByLabel('Battlefield')).toHaveValue('ironbreak-pass')
    await expect(menu.getByLabel('Time limit (minutes)')).toHaveValue('1')
    await menu.getByRole('button', { name: 'Close settings' }).tap()
    await page.getByRole('button', { name: 'Play vs Computer' }).tap()
    await expect(page.locator('#match-clock')).toBeVisible()
    await expect(page.locator('#gold')).toHaveText('123')
    const statistics = page.getByRole('button', { name: 'Match statistics' })
    await expect(statistics).toBeVisible({ timeout: 80_000 })
    await expect(page.locator('#battlefield canvas')).toBeVisible()
    await expect(page.locator('#result')).not.toBeVisible()
    await statistics.tap()
    await expect(page.getByRole('region', { name: 'Match statistics' })).toBeVisible()
    await expect(page.locator('#result-map')).toHaveText('Ironbreak Pass')
    await expect(page.locator('#result-detail')).toContainText('Time expired')
    await expect(page.getByRole('rowheader', { name: 'Gold gathered' })).toBeVisible()
    await expect(page.getByRole('rowheader', { name: 'Final score' })).toBeVisible()
    await expect(page.getByRole('rowheader', { name: 'Enemy buildings razed' })).toBeVisible()
    await expect(page.getByRole('rowheader', { name: 'Completed research' })).toBeVisible()
    await page.getByRole('button', { name: 'Play again' }).tap()
    await expect(page.locator('#result')).not.toBeVisible()
    await expect(page.locator('#gold')).toHaveText('123')
    page.once('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: 'Leave', exact: true }).tap()
    await expect(page.getByRole('button', { name: 'Play vs Computer' })).toBeVisible()
  } finally {
    await context.close()
    if (mobile !== browser) await mobile.close()
  }
})

test('practice teaches selection, mine inspection, training and attack-move while preserving the solo save', async ({ browser, baseURL }) => {
  const mobile = process.env.MOBILE_BROWSER === 'webkit' ? await webkit.launch() : browser
  const context = await mobile.newContext(devices[mobile === browser ? 'Pixel 7' : 'iPhone 14'])
  try {
    const page = await context.newPage()
    const saved = JSON.stringify({ version: 1, owner: 'previous', save: { faction: 'human' } })
    await page.addInitScript(value => localStorage.setItem('ash-and-iron-solo', value), saved)
    await page.goto(baseURL!)
    await page.getByRole('button', { name: 'Practice', exact: true }).tap()
    const hint = page.locator('#practice-hint')
    await expect(hint).toContainText('1/4')
    await page.getByRole('button', { name: 'Workers', exact: true }).tap()
    await expect(hint).toContainText('2/4')
    const field = page.locator('#battlefield')
    await expect(field.locator('canvas')).toBeVisible()
    await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    const box = (await field.boundingBox())!
    // The practice camera centers on the mine unless it reaches the left map edge.
    const mine = cellCenter(5, 18)
    await page.touchscreen.tap(box.x + Math.min(box.width / 2, mine.x * .88), box.y + box.height / 2)
    await page.touchscreen.tap(box.x + Math.min(box.width / 2, mine.x * .88), box.y + box.height / 2)
    await expect(hint).toContainText('3/4')
    await page.getByRole('button', { name: 'Production', exact: true }).tap()
    await page.getByRole('button', { name: 'Train 1 Footman', exact: true }).tap()
    await expect(hint).toContainText('4/4')
    await page.getByRole('button', { name: 'Close', exact: true }).tap()
    await page.getByRole('button', { name: 'All troops', exact: true }).tap()
    await page.getByRole('button', { name: 'Attack move', exact: true }).tap()
    const target = (await field.boundingBox())!
    await page.touchscreen.tap(target.x + target.width * .7, target.y + target.height * .47)
    await expect(hint).toContainText('Practice complete')
    await page.getByRole('button', { name: 'Finish practice', exact: true }).tap()
    await expect(page.getByRole('button', { name: 'Resume solo match' })).toBeVisible()
    expect(await page.evaluate(() => localStorage.getItem('ash-and-iron-solo'))).toBe(saved)
  } finally {
    await context.close()
    if (mobile !== browser) await mobile.close()
  }
})

test('army templates can be created, replenished and selected in practice', async ({ page, baseURL }) => {
  await page.goto(baseURL!)
  await page.getByRole('button', { name: 'Practice', exact: true }).click()
  await expect(page.locator('#battlefield canvas')).toBeVisible()
  await page.getByRole('button', { name: 'Production', exact: true }).click()
  await page.getByRole('button', { name: 'Army groups', exact: true }).click()
  const sheet = page.getByRole('dialog', { name: 'Army groups' })
  const currentSelection = await page.locator('#selection-name').textContent()
  const field = (await page.locator('#battlefield canvas').boundingBox())!
  await page.mouse.click(field.x + 6, field.y + 6)
  await expect(sheet).not.toBeVisible()
  await expect(page.locator('#selection-name')).toHaveText(currentSelection!)
  await page.getByRole('button', { name: 'Production', exact: true }).click()
  await page.getByRole('button', { name: 'Army groups', exact: true }).click()
  await sheet.getByRole('button', { name: 'New group' }).click()
  await sheet.getByLabel('Group name').fill('Vanguard')
  await sheet.getByLabel('Footman', { exact: true }).fill('1')
  await sheet.getByRole('button', { name: 'Save group' }).click()
  await expect(sheet).toContainText('Vanguard · 0/1')
  await sheet.getByRole('button', { name: 'Replenish', exact: true }).click()
  await expect(sheet).toContainText('Footman · 1 missing · 0 queued · +1 to queue')
  await sheet.getByRole('button', { name: 'Confirm replenish', exact: true }).click()
  await expect(sheet).toContainText('Vanguard · 1/1', { timeout: 12000 })
  await sheet.getByRole('button', { name: 'Select group', exact: true }).click()
  await expect(page.locator('#selection-name')).toHaveText('Footman')
})
